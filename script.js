// KEYBOARD CONTROLS
// ==========================================================

document.addEventListener("keydown", e => {

  const lightboxElement = $("#lightbox");

  if (
    !lightboxElement ||
    !lightboxElement.classList.contains("open")
  ) {

    return;

  }


  if (e.key === "Escape") {

    closeLightbox();

  }


  if (e.key === "ArrowRight") {

    nextLightbox();

  }


  if (e.key === "ArrowLeft") {

    prevLightbox();

  }

});


